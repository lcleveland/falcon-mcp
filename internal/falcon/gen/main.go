const (
	falconpyRev = "06a5df86bc68e492db339dccacdff4a9b9ad61ec" // 2026-09-24
	upstreamRev = "82d5031dddca464bb81d74bfec31fcc51a0d5854" // falcon-mcp v0.19.0
)

// extra are operations the tool table uses beyond upstream's scope map,
// mostly writes from the capability map that upstream does not expose.
var extra = map[string]string{
	"PerformActionV2":                       "Hosts:write",
	"indicator_update_v1":                   "IOC Management:write",
	"BatchInitSessions":                     "Real time response:read",
	"BatchRefreshSessions":                  "Real time response:read",
	"BatchCmd":                              "Real time response:read",
	"RTR_ExecuteActiveResponderCommand":     "Real time response:write",
	"RTR_CheckActiveResponderCommandStatus": "Real time response:write",
	"BatchActiveResponderCmd":               "Real time response:write",
	// Probe routes for read scopes upstream reaches only through POSTs,
	// required filters or write scopes.
	"query_hosts":          "Assets:read",
	"ListSavedQueries":     "NGSIEM:read",
	"QuerySensorsByFilter": "Identity Protection Entities:read",
	// Upstream's key for this predates FalconPy's rename; upstream also lists
	// four read scopes, but GraphQL:write is the one the call needs.
	"post_graphql": "Identity Protection GraphQL:write",
}

// dropped are upstream keys that are not FalconPy operation IDs.
var dropped = []string{"api_preempt_proxy_post_graphql", "aidr_events_query"}

// reads are the non-GET operations that change nothing, so they may be
// retried. Every other non-GET is a write. Falcon has many POST reads (ids in
// a body, aggregates), so the method alone is not enough.
var reads = []string{
	"PostEntitiesAlertsV2", "PostAggregatesAlertsV2", "PostDeviceDetailsV2",
	"entities_cases_post_v2", "aggregates_slas_post_v1", "aggregates_templates_post_v1",
	"aggregates_access_tags_post_v1", "aggregates_notification_groups_post_v2", "aggregates_file_details_post_v1",
	"RTR_ListSessions", "RTR_AggregateSessions", "GetQuarantineFiles",
	"AggregateNotificationsV1", "AggregateNotificationsExposedDataRecordsV1", "PreviewRuleV1",
	"StartSearchV1", "StopSearchV1", "post_graphql",
}

var (
	endpointRe = regexp.MustCompile(`\[\s*"(\w+)",\s*"(GET|POST|PUT|PATCH|DELETE)",\s*"([^"]+)"`)
	scopeRe    = regexp.MustCompile(`(?s)"(\w+)":\s*\[(.*?)\]`)
	quotedRe   = regexp.MustCompile(`"([^"]+)"`)
)

type route struct{ method, path, file string }

func main() {
	log.SetFlags(0)
	routes := falconpyRoutes()
	scopes := upstreamScopes()
	for id, s := range extra {
		scopes[id] = s
	}
	for id, r := range routes {
		if r.file == "_aidr.py" {
			scopes[id] = "AIDR:read"
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/falcon/gen from FalconPy %s and falcon-mcp %s; DO NOT EDIT.\n\npackage falcon\n\nvar ops = map[string]Op{\n", falconpyRev[:7], upstreamRev[:7])
	for _, id := range slices.Sorted(maps.Keys(scopes)) {
		r, ok := routes[id]
		if !ok {
			log.Fatalf("op %s has a scope but no FalconPy route", id)
		}
		write := r.method != http.MethodGet && !slices.Contains(reads, id)
		fmt.Fprintf(&b, "\t%q: {%q, %q, %q, %t},\n", id, r.method, r.path, scopes[id], write)
	}
	b.WriteString("}\n")
	for _, id := range reads {
		if _, ok := scopes[id]; !ok {
			log.Fatalf("reads lists %s, which is not in the table", id)
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("ops_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d ops", len(scopes))
	writeGuides()
}

//go:embed guides.py
var guidesPy []byte

// writeGuides replaces ../../guides/*.md with upstream's guides, one file per
// falcon:// URI, and copies upstream's licence beside them.
func writeGuides() {
	src, err := os.MkdirTemp("", "falcon-mcp-upstream")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(src)
	untar(fetch("https://codeload.github.com/CrowdStrike/falcon-mcp/tar.gz/"+upstreamRev), src)

	cmd := exec.Command("python3", "-", src)
	cmd.Stdin = bytes.NewReader(guidesPy)
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		log.Fatalf("extracting guides: %v", err)
	}
	var guides map[string]string
	if err := json.Unmarshal(out, &guides); err != nil {
		log.Fatal(err)
	}
	if len(guides) < 50 { // upstream had 54 at the pin
		log.Fatalf("only %d guides extracted; has falcon_mcp/resources changed?", len(guides))
	}

	const dir = "../../guides"
	// Stale guides would be embedded, so clear them first.
	old, _ := filepath.Glob(filepath.Join(dir, "*.md"))
	for _, f := range old {
		if err := os.Remove(f); err != nil {
			log.Fatal(err)
		}
	}
	for uri, text := range guides {
		name, ok := strings.CutPrefix(uri, "falcon://")
		if !ok || strings.Contains(name, ".") {
			log.Fatalf("unexpected guide URI %q", uri)
		}
		write(filepath.Join(dir, strings.ReplaceAll(name, "/", ".")+".md"), []byte(text))
	}
	lic, err := os.ReadFile(filepath.Join(src, "LICENSE"))
	if err != nil {
		log.Fatal(err)
	}
	write(filepath.Join(dir, "LICENSE"), append([]byte("Guides extracted from CrowdStrike/falcon-mcp "+upstreamRev+".\n\n"), lic...))
	log.Printf("wrote %d guides", len(guides))
}

// untar unpacks a GitHub tarball into dir, dropping its top-level folder.
func untar(tgz []byte, dir string) {
	gz, err := gzip.NewReader(bytes.NewReader(tgz))
	if err != nil {
		log.Fatal(err)
	}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return
		}
		if err != nil {
			log.Fatal(err)
		}
		_, rel, _ := strings.Cut(h.Name, "/")
		if h.Typeflag != tar.TypeReg || rel == "" || !filepath.IsLocal(rel) {
			continue
		}
		b, err := io.ReadAll(tr)
		if err != nil {
			log.Fatal(err)
		}
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			log.Fatal(err)
		}
		write(p, b)
	}
}

func write(p string, b []byte) {
	if err := os.WriteFile(p, b, 0o644); err != nil {
		log.Fatal(err)
	}
}

// falconpyRoutes parses every src/falconpy/_endpoint/*.py in the tarball.
func falconpyRoutes() map[string]route {
	gz, err := gzip.NewReader(bytes.NewReader(fetch("https://codeload.github.com/CrowdStrike/falconpy/tar.gz/" + falconpyRev)))
	if err != nil {
		log.Fatal(err)
	}
	routes := map[string]route{}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			log.Fatal(err)
		}
		dir, file := path.Split(h.Name)
		if !strings.HasSuffix(dir, "src/falconpy/_endpoint/") || !strings.HasPrefix(file, "_") || !strings.HasSuffix(file, ".py") {
			continue
		}
		body, err := io.ReadAll(tr)
		if err != nil {
			log.Fatal(err)
		}
		for _, m := range endpointRe.FindAllStringSubmatch(string(body), -1) {
			r := route{m[2], m[3], file}
			if old, ok := routes[m[1]]; ok && (old.method != r.method || old.path != r.path) {
				log.Fatalf("op %s has two routes: %s %s and %s %s", m[1], old.method, old.path, r.method, r.path)
			} else if !ok {
				routes[m[1]] = r
			}
		}
	}
	if len(routes) < 1000 {
		log.Fatalf("only %d FalconPy routes parsed; has the table format changed?", len(routes))
	}
	return routes
}

// upstreamScopes parses API_SCOPE_REQUIREMENTS. Every kept entry must list
// exactly one scope.
func upstreamScopes() map[string]string {
	src := string(fetch("https://raw.githubusercontent.com/CrowdStrike/falcon-mcp/" + upstreamRev + "/falcon_mcp/common/api_scopes.py"))
	start := strings.Index(src, "API_SCOPE_REQUIREMENTS = {")
	end := strings.Index(src[start:], "\n}\n")
	if start < 0 || end < 0 {
		log.Fatal("API_SCOPE_REQUIREMENTS not found in api_scopes.py")
	}
	scopes := map[string]string{}
	for _, m := range scopeRe.FindAllStringSubmatch(src[start:start+end], -1) {
		if slices.Contains(dropped, m[1]) {
			continue
		}
		q := quotedRe.FindAllStringSubmatch(m[2], -1)
		if len(q) != 1 {
			log.Fatalf("op %s lists %d scopes; add it to extra with the one the call needs", m[1], len(q))
		}
		scopes[m[1]] = q[0][1]
	}
	if len(scopes) < 200 {
		log.Fatalf("only %d upstream scopes parsed; has api_scopes.py changed?", len(scopes))
	}
	return scopes
}

func fetch(url string) []byte {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return b
}
